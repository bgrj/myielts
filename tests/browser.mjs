import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
const browser = await chromium.launch(process.env.CI ? {} : { executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const errors = [];
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.message));
const base = process.env.TEST_URL || 'http://127.0.0.1:4173/myielts/';
await mkdir('.test-artifacts', { recursive: true });
try {
  await page.goto(base);
  await page.getByRole('heading', { name: '每一句，都记住一点。' }).waitFor();
  await page.screenshot({ path: '.test-artifacts/mobile-today.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.equal(await page.locator('.stat-value').first().innerText(), '0');
  await page.getByRole('button', { name: '开始今日学习' }).click();
  await page.locator('#study-answer').fill('my own answer');
  await page.getByRole('button', { name: '回忆好了，核对答案' }).click();
  await page.getByRole('button', { name: /^记住/ }).click();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('myielts.state.v1')).events.length), 1);
  await page.getByRole('button', { name: '撤销上一条' }).click();
  assert.equal(await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('myielts.state.v1')).progress).length), 0);
  await page.getByRole('button', { name: /^记住/ }).click();
  for (let i = 0; i < 4; i++) {
    await page.getByRole('button', { name: '回忆好了，核对答案' }).click();
    await page.getByRole('button', { name: i === 0 ? /^忘了/ : /^记住/ }).click();
  }
  await page.getByRole('heading', { name: '这几句，又熟悉了一点。' }).waitFor();
  assert.equal(await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('myielts.state.v1')).progress).length), 5);
  await page.reload();
  await page.getByRole('heading', { name: '每一句，都记住一点。' }).waitFor();
  assert.equal(await page.locator('.stat-value').first().innerText(), '5');
  await page.getByRole('link', { name: '我的知识库' }).click();
  await page.locator('#library-search').fill('housing');
  await page.locator('[data-action="open-card"][data-id="c17-t1-p1-087"]').click();
  await page.getByRole('heading', { name: '回到原句里' }).waitFor();
  assert.ok((await page.locator('#card-dialog').innerText()).includes('原题 Notes Completion'));
  await page.locator('#card-dialog').getByRole('button', { name: /^收藏 housing/ }).click();
  await page.getByRole('button', { name: '关闭知识卡' }).click();
  await page.getByRole('link', { name: '随手练习' }).click();
  await page.locator('[data-action="lesson"][data-lesson="self-drive"]').click();
  assert.ok(await page.getByRole('button', { name: '播放', exact: true }).isVisible());
  await page.getByRole('button', { name: '回忆好了，核对答案' }).click();
  await page.getByRole('button', { name: /^记住/ }).click();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('myielts.state.v1')).events.length), 6);
  await page.getByRole('button', { name: '稍后继续' }).click();
  await page.getByRole('link', { name: '资料与设置' }).click();
  await page.locator('#daily-new').fill('7'); await page.locator('#daily-new').blur();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出完整备份' }).click();
  const download = await downloadPromise;
  await download.saveAs('.test-artifacts/backup.json');
  const exported = JSON.parse(await readFile('.test-artifacts/backup.json', 'utf8'));
  assert.equal(exported.cards.length, 370); assert.equal(exported.settings.dailyNew, 7);
  const originalEvents = exported.events.length;
  const restoreContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const restorePage = await restoreContext.newPage();
  await restorePage.goto(base + '#settings');
  await restorePage.locator('input[data-file="backup"]').setInputFiles('.test-artifacts/backup.json');
  await restorePage.waitForFunction(() => JSON.parse(localStorage.getItem('myielts.state.v1') || '{}').events?.length === 6);
  assert.equal(await restorePage.evaluate(() => JSON.parse(localStorage.getItem('myielts.state.v1')).settings.dailyNew), 7);
  await restoreContext.close();
  // Invalid imports must not partially write.
  const incoming = { schemaVersion: 1, cards: [{ ...exported.cards[0], id: 'qa-safe' }, { ...exported.cards[0], id: 'qa-bad', focus: 'nonexistent phrase' }] };
  await page.locator('#import-json').fill(JSON.stringify(incoming));
  await page.getByRole('button', { name: '导入知识卡', exact: true }).click();
  assert.ok((await page.locator('#import-error').innerText()).includes('focus'));
  assert.ok(!(await page.evaluate(() => JSON.parse(localStorage.getItem('myielts.state.v1')).cards)).some(c => c.id === 'qa-safe'));
  const valid = { schemaVersion: 1, cards: [{ ...exported.cards[0], id: 'qa-safe', target: '<img src=x onerror=alert(1)>', meaning: '验证导入的文本按纯文本显示' }] };
  await page.locator('#import-json').fill(JSON.stringify(valid));
  await page.getByRole('button', { name: '导入知识卡', exact: true }).click();
  await page.getByRole('link', { name: '我的知识库' }).click();
  await page.locator('#library-search').fill('验证导入');
  assert.equal(await page.locator('.library-card').count(), 1);
  assert.equal(await page.locator('.library-card img').count(), 0);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('myielts.state.v1')).events.length), originalEvents);
  await page.getByRole('link', { name: '资料与设置' }).click();
  await page.locator('#import-extra').selectOption('manual');
  await page.locator('[name="target"]').fill('in place');
  await page.locator('[name="meaning"]').fill('已经到位');
  await page.locator('[name="source"]').fill('剑雅 17 · Test 1 · Passage 1');
  await page.locator('[name="focus"]').fill('in place');
  await page.locator('[name="sentence"]').fill('By 1907, the heart of today’s Underground system was in place.');
  await page.getByRole('button', { name: '保存知识卡' }).click();
  assert.ok(await page.locator('#edit-dialog').isHidden());
  await page.getByRole('link', { name: '我的知识库' }).click();
  // Offline app shell + data, followed by a real search.
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true);
  await page.reload();
  await page.locator('#library-search').fill('congested');
  assert.ok(await page.locator('.library-card').count() > 0);
  await context.setOffline(false);
  await page.setViewportSize({ width: 360, height: 780 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await desktop.goto(base);
  await desktop.getByRole('heading', { name: '每一句，都记住一点。' }).waitFor();
  await desktop.screenshot({ path: '.test-artifacts/desktop-today.png', fullPage: true });
  assert.ok(await desktop.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: mobile/desktop layout, rating/undo, persistence, favorites, dictation, backup migration, atomic import, escaped content, manual entry, offline reload/search; no browser exceptions.');
} finally { await browser.close(); }
